"""
Shared pytest fixtures for GFIS data-quality tests.

A single read-only DuckDB connection is shared across the test session.
All tests must run against data/gfis.duckdb, which is regenerated by:
    python -m src.ingestion.load_to_duckdb
"""
from __future__ import annotations

from pathlib import Path

import duckdb
import pytest

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DB_PATH = PROJECT_ROOT / "data" / "gfis.duckdb"


@pytest.fixture(scope="session")
def con():
    """Read-only DuckDB connection, one per test session."""
    if not DB_PATH.exists():
        pytest.skip(f"DuckDB file not found at {DB_PATH}. "
                    "Run: python -m src.ingestion.load_to_duckdb")
    connection = duckdb.connect(str(DB_PATH), read_only=True)
    yield connection
    connection.close()


@pytest.fixture(scope="session")
def tables(con):
    """Set of all table names in the database."""
    rows = con.execute("""
        SELECT table_name FROM information_schema.tables
        WHERE table_schema = 'main'
    """).fetchall()
    return {r[0] for r in rows}